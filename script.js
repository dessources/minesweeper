/* ============================================================
   MINESWEEPER LOGIC - attendees do NOT edit this file.
   The classes JS adds to each cell are what we style in CSS:

   cell      every square
   open      a square that has been opened
   n1 - n8   the number inside an opened square
   flag      a square with a flag
   mine      a mine (shown when you lose)
   boom      the mine you clicked
   ============================================================ */

   const rows = 8;
   const cols = 10;
   const mines = 10;
   
   const boardEl      = document.getElementById('board');
   const flagsEl      = document.getElementById('flags');
   const timerEl      = document.getElementById('timer');
   const newBtn       = document.getElementById('new-btn');
   const overlayEl    = document.getElementById('overlay');
   const overlayIcons = document.getElementById('overlay-icons');
   const overlayText  = document.getElementById('overlay-text');
   
   let grid;            // 2D array: grid[row][col]
   let firstClick, gameOver;
   let flagsLeft, opened, seconds, timerId;
   
   /* ---------- Start a game ---------- */
   
   function newGame() {
     clearInterval(timerId);
     seconds = 0;
     opened = 0;
     flagsLeft = mines;
     firstClick = true;
     gameOver = false;
   
     boardEl.innerHTML = '';
     boardEl.classList.remove('over');
   
     // Build the 2D array and the matching HTML squares
     grid = [];
     for (let r = 0; r < rows; r++) {
       const row = [];
       for (let c = 0; c < cols; c++) {
         const el = document.createElement('div');
         el.className = 'cell';
   
         el.addEventListener('click', () => openCell(r, c));
         el.addEventListener('contextmenu', (e) => {
           e.preventDefault();
           toggleFlag(r, c);
         });
   
         boardEl.appendChild(el);
         row.push({ r, c, el, mine: false, open: false, flag: false, count: 0 });
       }
       grid.push(row);
     }
   
     updateStats();
     showOverlay('▶', '');
   }
   
   /* ---------- Mines ---------- */
   
   // Mines are placed after the first click so the first click is always safe
   function placeMines(safeR, safeC) {
     let placed = 0;
     while (placed < mines) {
       const r = Math.floor(Math.random() * rows);
       const c = Math.floor(Math.random() * cols);
       const nearStart = Math.abs(r - safeR) <= 1 && Math.abs(c - safeC) <= 1;
       if (!grid[r][c].mine && !nearStart) {
         grid[r][c].mine = true;
         placed++;
       }
     }
     for (const row of grid) {
       for (const cell of row) {
         cell.count = neighbors(cell).filter(n => n.mine).length;
       }
     }
   }
   
   function neighbors(cell) {
     const list = [];
     for (let dr = -1; dr <= 1; dr++) {
       for (let dc = -1; dc <= 1; dc++) {
         if (dr === 0 && dc === 0) continue;
         const r = cell.r + dr;
         const c = cell.c + dc;
         if (r >= 0 && r < rows && c >= 0 && c < cols) list.push(grid[r][c]);
       }
     }
     return list;
   }
   
   /* ---------- Clicking ---------- */
   
   function openCell(r, c) {
     if (gameOver) return;
     hideOverlay();
   
     const cell = grid[r][c];
     if (cell.open || cell.flag) return;
   
     if (firstClick) {
       placeMines(r, c);
       firstClick = false;
       timerId = setInterval(() => { seconds++; updateStats(); }, 1000);
     }
   
     if (cell.mine) return lose(cell);
   
     reveal(cell);
     if (opened === rows * cols - mines) win();
   }
   
   // Opens a square. If it has 0 mines nearby, it opens its neighbors too.
   function reveal(cell) {
     if (cell.open || cell.flag || cell.mine) return;
   
     cell.open = true;
     opened++;
     cell.el.classList.add('open');
   
     if (cell.count > 0) {
       cell.el.classList.add('n' + cell.count);
       cell.el.textContent = cell.count;
       return;
     }
     neighbors(cell).forEach(reveal);
   }
   
   function toggleFlag(r, c) {
     if (gameOver) return;
     hideOverlay();
   
     const cell = grid[r][c];
     if (cell.open) return;
   
     cell.flag = !cell.flag;
     flagsLeft += cell.flag ? -1 : 1;
     cell.el.classList.toggle('flag', cell.flag);
     cell.el.textContent = cell.flag ? '⚑' : '';
     updateStats();
   }
   
   /* ---------- Ending ---------- */
   
   function lose(hitCell) {
     endGame();
     hitCell.el.classList.add('boom');
     for (const row of grid) {
       for (const cell of row) {
         if (cell.mine) {
           cell.el.classList.add('mine');
           cell.el.textContent = '✸';
         }
       }
     }
     showOverlay('✕', 'Game over. Click to play again.');
   }

   function win() {
     endGame();
     showOverlay('★', `You win in ${seconds}s! Click to play again.`);
   }
   
   function endGame() {
     gameOver = true;
     clearInterval(timerId);
     boardEl.classList.add('over');
   }
   
   /* ---------- Little helpers ---------- */
   
   function updateStats() {
     flagsEl.textContent = flagsLeft;
     timerEl.textContent = String(Math.min(seconds, 999)).padStart(3, '0');
   }
   
   function showOverlay(icons, text) {
     overlayIcons.textContent = icons;
     overlayText.textContent = text;
     overlayEl.classList.remove('hidden');
   }
   
   function hideOverlay() {
     overlayEl.classList.add('hidden');
   }
   
   /* ---------- Buttons ---------- */
   
   overlayEl.addEventListener('click', () => {
     if (gameOver) newGame();
     hideOverlay();
   });
   
   newBtn.addEventListener('click', newGame);
   
   newGame();